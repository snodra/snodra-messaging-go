package snodra

import (
	"testing"
	"time"
)

func TestDefaultTimings(t *testing.T) {
	d := defaultTimings()
	is(t, d.heartbeatBeforeAck, 3*s)
	is(t, d.handshakeTimeout, 10*s)
	is(t, d.silentIntervals, 3)
	is(t, d.keepaliveTime, 10*s)
	is(t, d.keepaliveTimeout, 5*s)
	is(t, d.backoffMin, 500*ms)
	is(t, d.backoffMax, 5*s)
	is(t, d.deregisterWait, 1*s)
	is(t, d.handlerDrain, 5*s)
	is(t, d.subscriptionEnd, 2*s)
	is(t, d.closeWait, 2*s)
	is(t, d.permitFlushAfter, 50*ms)
	is(t, permitBatch, uint32(16))
	is(t, guardMargin, 1*s)
	is(t, fallbackMaxTimeout, 60*s)
	is(t, defaultBudget, 5*s)
	is(t, retryMinRemaining, 250*ms)
	is(t, outboundLimit, 256)
	is(t, jwksMinRefresh, 60*s)
	is(t, jwksFetchTimeout, 5*s)
	is(t, d.certCheckInterval, 3*s)
	is(t, d.rollDelayMax, 30*s)
	is(t, d.rollIdleLimit, 10*s)
	is(t, d.rollReconnectLimit, 30*s)
	is(t, tokenFetchTimeout, 10*s)
	is(t, defaultTokenLifetime, 60*s)
	is(t, minRefreshMargin, 5*s)
	is(t, tokenRetryMin, 1*s)
	is(t, tokenRetryMax, 30*s)
	is(t, tokenWakeInterval, 5*s)
	is(t, rollSettle, 50*ms)
	is(t, rollPoll, 10*ms)
	is(t, hubPoll, 100*ms)
	is(t, d.tokenFetchWait, 11*s)
	is(t, d.creditWait, 10*time.Minute)
	is(t, defaultCredit, uint32(64))
	is(t, defaultMaxSubscriptions, 1024)
	is(t, defaultConfig().maxSubscriptions, 1024)
}
